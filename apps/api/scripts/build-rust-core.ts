import { execSync } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';

const apiRoot = path.resolve(__dirname, '..');
const crateManifest = path.join(apiRoot, 'rust-quant-core', 'Cargo.toml');
const wasmOutputPath = path.join(
  apiRoot,
  'rust-quant-core',
  'target',
  'wasm32-unknown-unknown',
  'release',
  'quant_core.wasm',
);
const targetTsPath = path.join(
  apiRoot,
  'src',
  'market',
  'rust-core',
  'quant-core-wasm.bytes.ts',
);

function main() {
  console.log('[build:rust] Building quant_core (wasm32-unknown-unknown --release)...');
  execSync(
    `cargo build --manifest-path "${crateManifest}" --target wasm32-unknown-unknown --release`,
    { stdio: 'inherit', cwd: apiRoot },
  );

  if (!fs.existsSync(wasmOutputPath)) {
    throw new Error(`Expected WASM binary not found at ${wasmOutputPath}`);
  }

  const wasmBytes = fs.readFileSync(wasmOutputPath);
  const base64 = wasmBytes.toString('base64');

  fs.mkdirSync(path.dirname(targetTsPath), { recursive: true });
  const generatedContent = [
    '// Auto-generated by scripts/build-rust-core.ts. Do not edit manually.',
    `// Source: apps/api/rust-quant-core/src/lib.rs (${wasmBytes.length} bytes)`,
    `export const QUANT_CORE_WASM_BASE64 = '${base64}';`,
    '',
  ].join('\n');

  fs.writeFileSync(targetTsPath, generatedContent, 'utf8');
  console.log(
    `[build:rust] Generated ${path.relative(apiRoot, targetTsPath)} (${wasmBytes.length} bytes raw WASM).`,
  );
}

main();
